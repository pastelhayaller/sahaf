export function kategoriRehberi(key) {
  return kategoriGecerli(key) ? KATEGORI_REHBERI[key] : null;
}

// A recommendation is another title, with an exact recorded author/category match.
export function ilgiliKitaplar(kitap, adaylar, tur, haric = []) {
  const kimlik = k => String(k.ad || '').trim().toLocaleLowerCase('tr-TR') + '|' + String(k.yazar || '').trim().toLocaleLowerCase('tr-TR');
  const gorulen = new Set([kimlik(kitap), ...haric.map(kimlik)]);
  return [...adaylar].sort((a,b) => Number(!a.foto_url) - Number(!b.foto_url)).filter(k => {
    const eslesir = tur === 'yazar' ? kitap.yazar && k.yazar === kitap.yazar : kategoriGecerli(kitap.kategori) && k.kategori === kitap.kategori;
    const key = kimlik(k);
    if (!eslesir || String(k.id) === String(kitap.id) || gorulen.has(key)) return false;
    gorulen.add(key); return true;
  }).slice(0,4);
}
